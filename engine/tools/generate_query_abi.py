#!/usr/bin/env python3
"""Generate the shared query ABI constants for C and Rust."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "abi" / "query_abi_constants.json"
RUST_OUTPUT = ROOT / "src" / "query_abi_constants.rs"
C_OUTPUT = ROOT / "include" / "prdb_query_abi_constants.h"


def render(schema):
    constants = schema.get("constants")
    if not isinstance(constants, list) or not constants:
        raise ValueError("schema must contain a non-empty constants list")

    rust_names = set()
    c_names = set()
    rust_lines = ["// Generated by engine/tools/generate_query_abi.py; do not edit."]
    c_lines = [
        "/* Generated by engine/tools/generate_query_abi.py; do not edit. */",
        "#ifndef PRDB_QUERY_ABI_CONSTANTS_H",
        "#define PRDB_QUERY_ABI_CONSTANTS_H",
        "",
        "#include <stdint.h>",
        "",
    ]

    for item in constants:
        rust_name = item["rust_name"]
        rust_type = item["rust_type"]
        value = item["value"]
        c_name = item["c_name"]
        c_type = item["c_type"]
        if rust_name in rust_names or c_name in c_names:
            raise ValueError("constant names must be unique")
        rust_names.add(rust_name)
        c_names.add(c_name)

        if rust_type == "&str" and c_type == "string" and isinstance(value, str):
            escaped = json.dumps(value)
            rust_value = escaped
            c_value = escaped
        elif rust_type in ("u32", "u64") and c_type in ("UINT32_C", "UINT64_C"):
            expected_c_type = "UINT32_C" if rust_type == "u32" else "UINT64_C"
            if c_type != expected_c_type or not isinstance(value, int) or value < 0:
                raise ValueError(f"invalid integer constant {rust_name}")
            rust_value = str(value)
            c_value = f"{c_type}({value})"
        else:
            raise ValueError(f"unsupported type mapping for {rust_name}")

        rust_lines.append(f"pub const {rust_name}: {rust_type} = {rust_value};")
        c_lines.append(f"#define {c_name} {c_value}")

    c_lines.extend(["", "#endif /* PRDB_QUERY_ABI_CONSTANTS_H */", ""])
    rust_lines.append("")
    return "\n".join(rust_lines), "\n".join(c_lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    rust_text, c_text = render(schema)
    outputs = ((RUST_OUTPUT, rust_text), (C_OUTPUT, c_text))
    stale = []
    for path, generated in outputs:
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != generated:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(generated, encoding="utf-8")
    if stale:
        raise SystemExit("generated query ABI files are stale: " + ", ".join(map(str, stale)))


if __name__ == "__main__":
    main()
