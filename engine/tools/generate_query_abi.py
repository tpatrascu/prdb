#!/usr/bin/env python3
"""Generate shared query ABI and IPC declarations/constants for C and Rust."""

import argparse
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "abi" / "query_abi_constants.json"
RUST_OUTPUT = ROOT / "src" / "query_abi_constants.rs"
C_OUTPUT = ROOT / "include" / "prdb_query_abi_constants.h"
RUST_LAYOUT_OUTPUT = ROOT / "src" / "query_abi_layout_assertions.rs"
C_LAYOUT_OUTPUT = ROOT / "include" / "prdb_query_abi_layout_assertions.h"
IPC_OPERATION_CASES_OUTPUT = ROOT / "include" / "prdb_ipc_operation_cases_v1.h"
C_PAYLOAD_CODECS_OUTPUT = ROOT / "include" / "prdb_query_abi_payload_codecs.h"
RUST_RECORDS_OUTPUT = ROOT / "src" / "query_abi_records.rs"
C_RECORD_OUTPUTS = {
    "1": ROOT / "include" / "prdb_query_abi_records_v1.h",
    "2": ROOT / "include" / "prdb_query_abi_records_v2.h",
    "3": ROOT / "include" / "prdb_query_abi_records_v3.h",
    "4": ROOT / "include" / "prdb_query_abi_records_v4.h",
}


def render(schema):
    constants = schema.get("constants")
    if not isinstance(constants, list) or not constants:
        raise ValueError("schema must contain a non-empty constants list")

    rust_names = set()
    c_names = set()
    rust_lines = ["// Generated by engine/tools/generate_query_abi.py; do not edit."]
    c_lines = [
        "/* Generated by engine/tools/generate_query_abi.py; do not edit. */",
        "#ifndef PRDB_QUERY_ABI_CONSTANTS_H",
        "#define PRDB_QUERY_ABI_CONSTANTS_H",
        "",
        "#include <stdint.h>",
        "",
    ]
    c_codec_lines = [
        "/* Generated by engine/tools/generate_query_abi.py; do not edit. */",
        "#ifndef PRDB_QUERY_ABI_PAYLOAD_CODECS_H",
        "#define PRDB_QUERY_ABI_PAYLOAD_CODECS_H",
        "",
        '#include "prdb_query_abi_constants.h"',
        "#include <stddef.h>",
        "#include <stdint.h>",
        "",
    ]

    for item in constants:
        rust_name = item["rust_name"]
        rust_type = item["rust_type"]
        value = item["value"]
        c_name = item["c_name"]
        c_type = item["c_type"]
        if rust_name in rust_names or c_name in c_names:
            raise ValueError("constant names must be unique")
        rust_names.add(rust_name)
        c_names.add(c_name)

        if rust_type == "&str" and c_type == "string" and isinstance(value, str):
            escaped = json.dumps(value)
            rust_value = escaped
            c_value = escaped
        elif rust_type in ("u8", "u16", "u32", "u64") and c_type in (
            "UINT8_C",
            "UINT16_C",
            "UINT32_C",
            "UINT64_C",
        ):
            expected_c_type = {
                "u8": "UINT8_C",
                "u16": "UINT16_C",
                "u32": "UINT32_C",
                "u64": "UINT64_C",
            }[rust_type]
            maximum = {"u8": 0xFF, "u16": 0xFFFF, "u32": 0xFFFFFFFF, "u64": 0xFFFFFFFFFFFFFFFF}[rust_type]
            if c_type != expected_c_type or not isinstance(value, int) or not 0 <= value <= maximum:
                raise ValueError(f"invalid integer constant {rust_name}")
            rust_value = str(value)
            c_value = f"{c_type}({value})"
        else:
            raise ValueError(f"unsupported type mapping for {rust_name}")

        rust_lines.append(f"pub const {rust_name}: {rust_type} = {rust_value};")
        c_lines.append(f"#define {c_name} {c_value}")

    payload_schemas = schema.get("payload_schemas")
    if not isinstance(payload_schemas, list) or not payload_schemas:
        raise ValueError("schema must contain at least one IPC payload schema")
    payload_names = set()
    constants_by_name = {item["rust_name"]: item for item in constants}
    for payload in payload_schemas:
        name = payload.get("name")
        version_constant = payload.get("version_constant")
        fields = payload.get("fields")
        trailing_fields = payload.get("trailing_fields")
        if (
            not isinstance(name, str)
            or not name.isidentifier()
            or name in payload_names
            or not isinstance(fields, list)
            or not fields
            or not isinstance(trailing_fields, list)
        ):
            raise ValueError("invalid IPC payload schema")
        if version_constant not in constants_by_name:
            raise ValueError(f"unknown payload version constant for {name}")
        version_field = fields[0]
        version_item = constants_by_name[version_constant]
        if (
            version_field.get("name") != "version"
            or version_field.get("encoding") != "u16be"
            or version_item.get("rust_type") != "u16"
            or not isinstance(version_item.get("value"), int)
            or not 0 <= version_item["value"] <= 0xFFFF
        ):
            raise ValueError(f"payload {name} must start with its u16 version constant")
        payload_names.add(name)
        field_names = set()
        field_offsets = {}
        offset = 0
        field_widths = {
            "u8": 1,
            "u16be": 2,
            "u32be": 4,
            "u64be": 8,
            "i64be": 8,
            "bytes16": 16,
        }
        for field in fields:
            field_name = field.get("name")
            if (
                not isinstance(field_name, str)
                or not field_name.isidentifier()
                or field_name in field_names
                or field.get("encoding") not in field_widths
            ):
                raise ValueError(f"invalid fixed field in IPC payload {name}")
            field_names.add(field_name)
            field_offsets[field_name] = offset
            constant_stem = f"{name}_{field_name.upper()}_OFFSET"
            rust_name = constant_stem
            c_name = f"PRDB_{constant_stem}"
            if rust_name in rust_names or c_name in c_names:
                raise ValueError(f"duplicate generated IPC field constant {constant_stem}")
            rust_names.add(rust_name)
            c_names.add(c_name)
            rust_lines.append(f"pub const {rust_name}: u32 = {offset};")
            c_lines.append(f"#define {c_name} UINT32_C({offset})")
            offset += field_widths[field["encoding"]]
        length_fields = {
            field["name"]
            for field in fields
            if field["name"].endswith(("_length", "_count"))
        }
        fields_by_name = {field["name"]: field for field in fields}
        trailing_names = set()
        for field in trailing_fields:
            field_name = field.get("name")
            encoding = field.get("encoding")
            length_field = field.get("length_field")
            if (
                not isinstance(field_name, str)
                or not field_name.isidentifier()
                or field_name in trailing_names
                or encoding not in (
                    "utf8",
                    "bytes",
                    "bytes16_array",
                    "u64_triplet_array",
                )
                or length_field not in length_fields
            ):
                raise ValueError(f"invalid trailing field in IPC payload {name}")
            if (
                encoding in ("bytes16_array", "u64_triplet_array")
                and fields_by_name[length_field].get("encoding") != "u16be"
            ):
                raise ValueError(f"collection {field_name} must use a u16 count")
            if (
                encoding == "bytes"
                and fields_by_name[length_field].get("encoding") != "u32be"
            ):
                raise ValueError(f"byte payload {field_name} must use a u32 length")
            trailing_names.add(field_name)
        header_name = f"{name}_HEADER_BYTES"
        c_header_name = f"PRDB_{header_name}"
        if header_name in rust_names or c_header_name in c_names:
            raise ValueError(f"duplicate generated IPC header constant {header_name}")
        rust_names.add(header_name)
        c_names.add(c_header_name)
        rust_lines.append(f"pub const {header_name}: u32 = {offset};")
        c_lines.append(f"#define {c_header_name} UINT32_C({offset})")

        generate_rust_codec = payload.get("generate_rust_codec", False)
        if not isinstance(generate_rust_codec, bool):
            raise ValueError(f"generate_rust_codec must be Boolean for {name}")
        generate_c_codec = payload.get("generate_c_codec", False)
        if not isinstance(generate_c_codec, bool):
            raise ValueError(f"generate_c_codec must be Boolean for {name}")
        codec_prefix = payload.get("codec_prefix", False)
        if not isinstance(codec_prefix, bool):
            raise ValueError(f"codec_prefix must be Boolean for {name}")
        if codec_prefix and not (generate_rust_codec or generate_c_codec):
            raise ValueError(f"codec_prefix requires a generated codec in {name}")
        if generate_rust_codec:
            if trailing_fields and not codec_prefix:
                raise ValueError(
                    f"generated fixed Rust codec cannot encode trailing fields in {name}"
                )
            rust_types = {
                "u8": "u8",
                "u16be": "u16",
                "u32be": "u32",
                "u64be": "u64",
                "i64be": "i64",
                "bytes16": "[u8; 16]",
            }
            encode_name = f"encode_{name.lower()}"
            decode_name = f"decode_{name.lower()}"
            value_fields = fields[1:]
            for field in fields:
                if field["encoding"] not in rust_types:
                    raise ValueError(f"unsupported generated Rust codec field in {name}")
            arguments = ", ".join(
                f"{field['name']}: {rust_types[field['encoding']]}" for field in value_fields
            )
            result_types = ", ".join(rust_types[field["encoding"]] for field in value_fields)
            result_type = (
                f"({result_types})"
                if len(value_fields) != 1
                else result_types
            )
            rust_lines.extend(
                [
                    f"pub fn {encode_name}({arguments}) -> [u8; {offset}] {{",
                    f"    let mut payload = [0u8; {offset}];",
                ]
            )
            for field in fields:
                field_name = field["name"]
                field_encoding = field["encoding"]
                field_offset = field_offsets[field_name]
                field_end = field_offset + field_widths[field_encoding]
                if field_name == "version":
                    rust_lines.append(
                        f"    payload[{field_offset}..{field_end}].copy_from_slice(&{version_constant}.to_be_bytes());"
                    )
                elif field_encoding == "u8":
                    rust_lines.append(f"    payload[{field_offset}] = {field_name};")
                elif field_encoding == "bytes16":
                    rust_lines.append(
                        f"    payload[{field_offset}..{field_end}].copy_from_slice(&{field_name});"
                    )
                else:
                    rust_lines.append(
                        f"    payload[{field_offset}..{field_end}].copy_from_slice(&{field_name}.to_be_bytes());"
                    )
            rust_lines.extend(["    payload", "}", ""])
            if len(value_fields) >= 4:
                rust_lines.append("#[allow(clippy::type_complexity)]")
            rust_lines.extend(
                [
                    f"pub fn {decode_name}(payload: &[u8]) -> Option<{result_type}> {{",
                    f"    if payload.len() {'<' if codec_prefix else '!='} {offset} || u16::from_be_bytes([payload[0], payload[1]]) != {version_constant} {{",
                    "        return None;",
                    "    }",
                ]
            )
            decoded_values = []
            for field in value_fields:
                field_name = field["name"]
                field_encoding = field["encoding"]
                field_offset = field_offsets[field_name]
                field_end = field_offset + field_widths[field_encoding]
                if field_encoding == "u8":
                    decoded_values.append(f"payload[{field_offset}]")
                elif field_encoding == "bytes16":
                    decoded_values.append(
                        f"payload[{field_offset}..{field_end}].try_into().ok()"
                        + ("" if len(value_fields) == 1 else "?")
                    )
                else:
                    decoded_values.append(
                        f"{rust_types[field_encoding]}::from_be_bytes(payload[{field_offset}..{field_end}].try_into().ok()?)"
                    )
            decoded = ", ".join(decoded_values)
            if len(decoded_values) == 1:
                decoded_field_encoding = value_fields[0]["encoding"]
                if decoded_field_encoding == "bytes16":
                    rust_lines.append(f"    {decoded}")
                else:
                    rust_lines.append(f"    Some({decoded})")
            else:
                rust_lines.append(f"    Some(({decoded}))")
            rust_lines.extend(["}", ""])

        if generate_c_codec:
            if trailing_fields and not codec_prefix:
                raise ValueError(f"generated fixed C codec cannot encode trailing fields in {name}")
            c_types = {
                "u8": "uint8_t",
                "u16be": "uint16_t",
                "u32be": "uint32_t",
                "u64be": "uint64_t",
                "i64be": "int64_t",
                "bytes16": "uint8_t",
            }
            value_fields = fields[1:]
            if any(field["encoding"] not in c_types for field in fields):
                raise ValueError(f"unsupported generated C codec field in {name}")
            encode_name = f"prdb_encode_{name.lower()}"
            decode_name = f"prdb_decode_{name.lower()}"
            c_version_constant = constants_by_name[version_constant]["c_name"]
            arguments = []
            for field in value_fields:
                field_name = field["name"]
                if field["encoding"] == "bytes16":
                    arguments.append(f"const uint8_t {field_name}[16]")
                else:
                    arguments.append(f"{c_types[field['encoding']]} {field_name}")
            encode_parameters = f",\n    {', '.join(arguments)}" if arguments else ""
            c_codec_lines.extend(
                [
                    f"static inline void {encode_name}(uint8_t payload[{offset}]{encode_parameters}) {{",
                ]
            )
            for field in fields:
                field_name = field["name"]
                field_encoding = field["encoding"]
                field_offset = field_offsets[field_name]
                field_end = field_offset + field_widths[field_encoding]
                if field_name == "version":
                    c_codec_lines.extend(
                        [
                            f"    payload[{field_offset}] = (uint8_t)(({c_version_constant} >> 8) & 0xffu);",
                            f"    payload[{field_offset + 1}] = (uint8_t)({c_version_constant} & 0xffu);",
                        ]
                    )
                elif field_encoding == "u8":
                    c_codec_lines.append(f"    payload[{field_offset}] = {field_name};")
                elif field_encoding == "bytes16":
                    c_codec_lines.extend(
                        [
                            "    for (size_t i = 0; i < 16; ++i) {",
                            f"        payload[{field_offset} + i] = {field_name}[i];",
                            "    }",
                        ]
                    )
                else:
                    c_codec_lines.extend(
                        [
                            f"    uint64_t {field_name}_wire = (uint64_t){field_name};",
                            f"    for (size_t i = 0; i < {field_widths[field_encoding]}; ++i) {{",
                            f"        payload[{field_offset} + i] = (uint8_t)({field_name}_wire >> (({field_widths[field_encoding]} - 1 - i) * 8));",
                            "    }",
                        ]
                    )
            c_codec_lines.extend(["}", ""])

            output_arguments = []
            for field in value_fields:
                field_name = field["name"]
                if field["encoding"] == "bytes16":
                    output_arguments.append(f"uint8_t {field_name}[16]")
                else:
                    output_arguments.append(f"{c_types[field['encoding']]} *{field_name}")
            decode_parameters = f",\n    {', '.join(output_arguments)}" if output_arguments else ""
            c_codec_lines.extend(
                [
                    f"static inline int {decode_name}(const uint8_t *payload, size_t payload_len{decode_parameters}) {{",
                    f"    if (payload == NULL || payload_len {'<' if codec_prefix else '!='} {offset}) {{",
                    "        return 0;",
                    "    }",
                    f"    if (payload[0] != (uint8_t)(({c_version_constant} >> 8) & 0xffu) ||",
                    f"        payload[1] != (uint8_t)({c_version_constant} & 0xffu)) {{",
                    "        return 0;",
                    "    }",
                ]
            )
            for field in value_fields:
                field_name = field["name"]
                field_encoding = field["encoding"]
                field_offset = field_offsets[field_name]
                if field_encoding == "bytes16":
                    c_codec_lines.extend(
                        [
                            "    if (" + field_name + " == NULL) {",
                            "        return 0;",
                            "    }",
                            "    for (size_t i = 0; i < 16; ++i) {",
                            f"        {field_name}[i] = payload[{field_offset} + i];",
                            "    }",
                        ]
                    )
                else:
                    c_codec_lines.append(f"    if ({field_name} == NULL) {{")
                    c_codec_lines.append("        return 0;")
                    c_codec_lines.append("    }")
                    if field_encoding == "u8":
                        c_codec_lines.append(f"    *{field_name} = payload[{field_offset}];")
                    else:
                        width = field_widths[field_encoding]
                        c_codec_lines.extend(
                            [
                                f"    uint64_t {field_name}_wire_value = 0;",
                                f"    for (size_t i = 0; i < {width}; ++i) {{",
                                f"        {field_name}_wire_value = ({field_name}_wire_value << 8) | payload[{field_offset} + i];",
                                "    }",
                            ]
                        )
                        if field_encoding == "i64be":
                            c_codec_lines.extend(
                                [
                                    f"    if ({field_name}_wire_value <= (uint64_t)INT64_MAX) {{",
                                    f"        *{field_name} = (int64_t){field_name}_wire_value;",
                                    "    } else {",
                                    f"        *{field_name} = -1 - (int64_t)(UINT64_MAX - {field_name}_wire_value);",
                                    "    }",
                                ]
                            )
                        else:
                            c_codec_lines.append(
                                f"    *{field_name} = ({c_types[field_encoding]}){field_name}_wire_value;"
                            )
            c_codec_lines.extend(["    return 1;", "}", ""])

    constant_values = {item["rust_name"]: item["value"] for item in constants}
    frame_fields = (
        ("IPC_FRAME_MAGIC_OFFSET", "IPC_FRAME_MAGIC_LEN", "IPC_FRAME_VERSION_OFFSET"),
        ("IPC_FRAME_VERSION_OFFSET", "IPC_FRAME_VERSION_LEN", "IPC_FRAME_OPERATION_OFFSET"),
        ("IPC_FRAME_OPERATION_OFFSET", "IPC_FRAME_OPERATION_LEN", "IPC_FRAME_REQUEST_ID_OFFSET"),
        ("IPC_FRAME_REQUEST_ID_OFFSET", "IPC_FRAME_REQUEST_ID_LEN", "IPC_FRAME_PAYLOAD_LEN_OFFSET"),
        ("IPC_FRAME_PAYLOAD_LEN_OFFSET", "IPC_FRAME_PAYLOAD_LEN_LEN", "IPC_FRAME_HEADER_LEN"),
    )
    for offset_name, length_name, next_offset_name in frame_fields:
        try:
            offset = constant_values[offset_name]
            length = constant_values[length_name]
            next_offset = constant_values[next_offset_name]
        except KeyError as error:
            raise ValueError(f"missing IPC frame constant {error.args[0]}") from error
        if not all(isinstance(value, int) for value in (offset, length, next_offset)):
            raise ValueError(f"IPC frame offsets and lengths must be integers: {offset_name}")
        if length <= 0 or offset < 0 or offset + length != next_offset:
            raise ValueError(f"IPC frame field is not contiguous: {offset_name}")
    if constant_values.get("IPC_FRAME_MAGIC") != 0x50524449:
        raise ValueError("IPC frame magic must encode the canonical PRDI bytes")
    if constant_values.get("IPC_FRAME_VERSION") != 1:
        raise ValueError("IPC frame version must be 1")
    max_payload = constant_values.get("IPC_FRAME_MAX_PAYLOAD_BYTES")
    if not isinstance(max_payload, int) or not 0 < max_payload <= 0xFFFFFFFF:
        raise ValueError("IPC frame payload cap must fit the u32 wire field")
    frame_statuses = (
        "IPC_FRAME_STATUS_INVALID_MAGIC",
        "IPC_FRAME_STATUS_UNSUPPORTED_VERSION",
        "IPC_FRAME_STATUS_INVALID_OPERATION",
        "IPC_FRAME_STATUS_UNKNOWN_OPERATION",
        "IPC_FRAME_STATUS_INVALID_REQUEST_ID",
        "IPC_FRAME_STATUS_PAYLOAD_TOO_LARGE",
        "IPC_FRAME_STATUS_TRUNCATED",
    )
    status_values = [constant_values.get(name) for name in frame_statuses]
    if status_values != list(range(2, 9)):
        raise ValueError("IPC frame error statuses must preserve the canonical v1 mapping")
    gateway_error_payloads = {
        "IPC_GATEWAY_ERROR_INVALID_REQUEST":
            '{"code":"invalid_request","message":"Request is invalid."}',
        "IPC_GATEWAY_ERROR_INVALID_STATE":
            '{"code":"invalid_state","message":"Request is not valid in the current session state."}',
        "IPC_GATEWAY_ERROR_UNAUTHENTICATED":
            '{"code":"unauthenticated","message":"Authentication is required."}',
        "IPC_GATEWAY_ERROR_RESOURCE_LIMIT":
            '{"code":"resource_limit","message":"Request exceeds a configured limit."}',
        "IPC_GATEWAY_ERROR_UNAVAILABLE":
            '{"code":"unavailable","message":"Requested resource is unavailable."}',
    }
    if any(constant_values.get(name) != value for name, value in gateway_error_payloads.items()):
        raise ValueError("IPC gateway error payloads must preserve the canonical v1 schema")

    c_lines.extend(["", "#endif /* PRDB_QUERY_ABI_CONSTANTS_H */", ""])
    c_codec_lines.extend(["#endif /* PRDB_QUERY_ABI_PAYLOAD_CODECS_H */", ""])
    rust_lines.append("")
    ipc_operation_cases = [
        item for item in constants if item["rust_name"].startswith("IPC_OP_")
    ]
    if not ipc_operation_cases:
        raise ValueError("schema must define IPC operation tags")
    ipc_operation_cases_text = "\n".join(
        ["/* Generated by engine/tools/generate_query_abi.py; do not edit. */"]
        + [f"PRDB_IPC_OPERATION_CASE({item['c_name']})" for item in ipc_operation_cases]
        + [""]
    )

    layouts = schema.get("layouts")
    if not isinstance(layouts, list) or not layouts:
        raise ValueError("schema must contain a non-empty layouts list")
    rust_layout_lines = [
        "// Generated by engine/tools/generate_query_abi.py; do not edit.",
    ]
    c_layout_lines = [
        "/* Generated by engine/tools/generate_query_abi.py; do not edit. */",
        "#ifndef PRDB_QUERY_ABI_LAYOUT_ASSERTIONS_H",
        "#define PRDB_QUERY_ABI_LAYOUT_ASSERTIONS_H",
        "",
        "#include <stddef.h>",
        "",
    ]
    c_types = set()
    rust_types = set()
    rust_record_lines = ["// Generated by engine/tools/generate_query_abi.py; do not edit."]
    c_record_lines = {
        version: [
            "/* Generated by engine/tools/generate_query_abi.py; do not edit. */",
            f"#ifndef PRDB_QUERY_ABI_RECORDS_V{version}_H",
            f"#define PRDB_QUERY_ABI_RECORDS_V{version}_H",
            "",
        ]
        for version in C_RECORD_OUTPUTS
    }
    for layout in layouts:
        c_type = layout["c_type"]
        rust_type = layout["rust_type"]
        version = layout["version"]
        size = layout["size"]
        alignment = layout["alignment"]
        fields = layout["fields"]
        if c_type in c_types or rust_type in rust_types:
            raise ValueError("layout type names must be unique")
        if not isinstance(size, int) or size <= 0 or not isinstance(alignment, int) or alignment <= 0:
            raise ValueError(f"invalid size/alignment for {c_type}")
        if not isinstance(fields, list) or not fields:
            raise ValueError(f"layout {c_type} must have fields")
        c_types.add(c_type)
        rust_types.add(rust_type)
        if version not in C_RECORD_OUTPUTS:
            raise ValueError(f"unsupported declaration version {version}")
        if layout["kind"] == "alias":
            rust_record_lines.append(f"pub type {rust_type} = {layout['alias_rust_type']};")
            c_record_lines[version].append(f"typedef {layout['alias_c_type']} {c_type};")
        elif layout["kind"] == "record":
            derives = ", ".join(layout["derives"])
            rust_record_lines.extend(["#[repr(C)]", f"#[derive({derives})]", f"pub struct {rust_type} {{"])
            c_record_lines[version].append(f"typedef struct {c_type} {{")
            for field in layout["fields"]:
                rust_record_lines.append(f"    pub {field['rust_name']}: {field['rust_type']},")
                c_record_lines[version].append(f"    {field['c_type']} {field['c_name']};")
            rust_record_lines.extend(["}", ""])
            c_record_lines[version].extend([f"}} {c_type};", ""])
        else:
            raise ValueError(f"unsupported declaration kind for {c_type}")
        rust_layout_lines.extend(
            [
                f"const _: [(); {size}] = [(); core::mem::size_of::<{rust_type}>()];",
                f"const _: [(); {alignment}] = [(); core::mem::align_of::<{rust_type}>()];",
            ]
        )
        c_layout_lines.extend(
            [
                f'_Static_assert(sizeof({c_type}) == {size}, "{c_type} size");',
                f'_Static_assert(_Alignof({c_type}) == {alignment}, "{c_type} alignment");',
            ]
        )
        seen_fields = set()
        for field in fields:
            name = field["name"]
            offset = field["offset"]
            if name in seen_fields or not isinstance(offset, int) or offset < 0:
                raise ValueError(f"invalid field {name} in {c_type}")
            seen_fields.add(name)
            rust_layout_lines.append(
                f"const _: [(); {offset}] = [(); core::mem::offset_of!({rust_type}, {name})];"
            )
            c_layout_lines.append(
                f'_Static_assert(offsetof({c_type}, {name}) == {offset}, "{c_type}.{name} offset");'
            )
        rust_layout_lines.append("")
        c_layout_lines.append("")
    c_layout_lines.extend(
        ["#endif /* PRDB_QUERY_ABI_LAYOUT_ASSERTIONS_H */", ""]
    )
    rust_layout_lines.append("")
    rust_record_lines.append("")
    for version, lines in c_record_lines.items():
        lines.extend(["#endif", ""])
    return (
        "\n".join(rust_lines).rstrip() + "\n",
        "\n".join(c_lines),
        "\n".join(c_codec_lines),
        "\n".join(rust_layout_lines),
        "\n".join(c_layout_lines),
        "\n".join(rust_record_lines),
        {version: "\n".join(lines) for version, lines in c_record_lines.items()},
        ipc_operation_cases_text,
    )


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="fail if generated files are stale")
    args = parser.parse_args()
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    (
        rust_text,
        c_text,
        c_payload_codecs_text,
        rust_layout_text,
        c_layout_text,
        rust_records_text,
        c_records_text,
        ipc_operation_cases_text,
    ) = render(schema)
    outputs = (
        (RUST_OUTPUT, rust_text),
        (C_OUTPUT, c_text),
        (C_PAYLOAD_CODECS_OUTPUT, c_payload_codecs_text),
        (RUST_LAYOUT_OUTPUT, rust_layout_text),
        (C_LAYOUT_OUTPUT, c_layout_text),
        (RUST_RECORDS_OUTPUT, rust_records_text),
        *((C_RECORD_OUTPUTS[version], generated) for version, generated in c_records_text.items()),
        (IPC_OPERATION_CASES_OUTPUT, ipc_operation_cases_text),
    )
    stale = []
    for path, generated in outputs:
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != generated:
                stale.append(path.relative_to(ROOT))
        else:
            path.write_text(generated, encoding="utf-8")
    if stale:
        raise SystemExit("generated query ABI files are stale: " + ", ".join(map(str, stale)))


if __name__ == "__main__":
    main()
